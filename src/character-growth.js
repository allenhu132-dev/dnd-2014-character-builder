function spellTrack(job, level, subclass, pactAbility = 3) {
  if (level < 1) return null;
  const track = classGrowth[job];
  if (job === 'bloodhunter' && subclass === '渎魂结社' && level >= 3) {
    const slots = level < 6 ? '1' : level < 7 ? '2' : level < 13 ? '02' : level < 19 ? '002' : '0002';
    const known = level === 20 ? 11 : Math.floor((level + 1) / 2);
    return {stat: pactAbility, slots, known, cantrips: level < 10 ? 2 : 3, pact: true};
  }
  if (job === 'rogue' && subclass === '诡术师' || job === 'fighter' && ['奥法骑士', 'Eldritch Knight'].includes(subclass)) {
    if (level < 3) return null;
    return {stat: 3, slots: thirdSlots[level], known: thirdKnown[level - 1],
      cantrips: job === 'rogue' ? (level < 10 ? 3 : 4) : (level < 10 ? 2 : 3)};
  }
  if (!track.track || track.track === 'half' && level < 2 && job !== 'artificer') return null;
  const cantrips = track.cantrips?.[level < 4 ? 0 : level < 10 ? 1 : 2] ?? 0;
  const known = track.known?.[level - 1] ?? 0;
  if (track.track === 'pact') {
    const count = level === 1 ? 1 : level < 11 ? 2 : level < 17 ? 3 : 4;
    return {stat: track.casting, slots: '0'.repeat(Math.min(4, Math.floor((level - 1) / 2))) + count, known, cantrips, pact: true};
  }
  if (job === 'artificer') {
    return {stat: track.casting, slots: level === 1 ? '2' : halfSlots[level], cantrips: level < 10 ? 2 : level < 14 ? 3 : 4, prepared: true};
  }
  return {stat: track.casting, slots: (track.track === 'full' ? fullSlots : halfSlots)[level], cantrips, known, prepared: track.prepared};
}

